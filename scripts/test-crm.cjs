const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = fs.readFileSync('app/crm/store.ts', 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const exportsObject = {};
vm.runInNewContext(js, {exports: exportsObject, require: name => name === 'react' ? {} : name === '../data' ? {listings: []} : name === '@/lib/supabase' ? {sharedCRMEnabled:true} : name === './shared-store' ? {} : (()=>{throw Error(name)})(), crypto: require('node:crypto').webcrypto, URL, Date, Number, String});
const {blankProperty,validatePropertyDraft,publishIssues,publicListing,getPublicListings} = exportsObject;
const p = blankProperty();
assert(publishIssues(p).length >= 7, 'Incomplete listing must be blocked');
p.price=-1;
assert(validatePropertyDraft(p).some(x=>x.includes('price')));
p.price=900000; p.title='Test home'; p.description='A fictional property description long enough for a publication test.';
p.photos=[{id:'photo',url:'https://example.com/photo.jpg',alt:'Sample home'}];
p.ownerId='private-owner'; p.notes='PRIVATE'; p.address='Private address';
p.mandateConfirmed=p.disclosureConfirmed=p.factsVerified=true;
assert.equal(publishIssues(p).length,0);
let dto=publicListing(p);
for(const key of ['notes','ownerId','commission','mandate','agent']) assert.equal(key in dto,false,key+' must stay private');
assert.equal(dto.address,''); p.showAddress=true; assert.equal(publicListing(p).address,'Private address');
p.video='javascript:alert(1)'; assert(validatePropertyDraft(p).length>0); p.video='';
p.mandateEnd='2000-01-01'; assert(publishIssues(p).some(x=>x.includes('expired'))); p.mandateEnd='';
assert.equal(getPublicListings({properties:[{...p,status:'Draft',publicSnapshot:dto}]}).length,0);
assert.equal(getPublicListings({properties:[{...p,status:'Published',publicSnapshot:dto}]}).length,1);
console.log('PASS: required publication fields, negative prices, private payload boundary, address visibility, unsafe URLs, expired mandate and publication visibility.');
