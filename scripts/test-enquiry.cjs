const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const ts=require('typescript');
const output={};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('app/business.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports:output,encodeURIComponent});
const {business,whatsapp,enquiryMessage}=output;
assert.equal(business.tel,'tel:+27716034542');
const message=enquiryMessage({name:'Sample & Test',email:'sample@example.com',enquiry_type:'buyer',budget:'900000',property_reference:'LH-001',source_url:'PRIVATE_TRACKING_URL',popia_consent:'on'});
assert(message.includes('Name: Sample & Test'));
assert(message.includes('Property reference: LH-001'));
assert(message.includes('Budget (R): 900000'));
assert(!message.includes('PRIVATE_TRACKING_URL'));
assert(!message.includes('popia_consent'));
const link=new URL(whatsapp(message));
assert.equal(link.hostname,'wa.me');
assert.equal(link.pathname,'/27716034542');
assert.equal(link.searchParams.get('text'),message);
const forms=fs.readFileSync('app/modern-forms.tsx','utf8');
assert(!forms.includes('if(sample){'));
assert(forms.includes('submitOnlineEnquiry(fields,requestId.current)'));
assert(forms.includes('Nothing has been sent yet.'));
assert(forms.includes('[consent,setConsent]=useState(false)'));
console.log('PASS: contact destination, message encoding, property/budget preservation, tracking exclusion, explicit send handoff and shared submission handoff.');
